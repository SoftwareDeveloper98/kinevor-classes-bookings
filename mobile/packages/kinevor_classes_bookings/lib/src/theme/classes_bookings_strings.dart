  /// Human label for a class type.
  String typeLabel(String type) => type == 'BodyPump' ? 'Body Pump' : type;

  /// Formats a full date such as `Thursday 22 October`.
  String fullDate(DateTime value) =>
      '${_weekdays[value.weekday - 1]} ${value.day} ${_months[value.month - 1]}';

  /// Formats a short month and day such as `Oct 22`.
  String monthDay(DateTime value) => '${_months[value.month - 1]} ${value.day}';

  /// Formats an uppercase weekday.
  String weekday(DateTime value) =>
      _weekdays[value.weekday - 1].substring(0, 3).toUpperCase();

  /// Formats an uppercase month.
  String month(DateTime value) =>
      _months[value.month - 1].substring(0, 3).toUpperCase();

  /// Formats a two-digit day.
  String day(DateTime value) => value.day.toString().padLeft(2, '0');

  /// Formats a 24-hour time.
  String time(DateTime value) =>
      '${value.hour.toString().padLeft(2, '0')}:'
      '${value.minute.toString().padLeft(2, '0')}';

  /// Formats a time range.
  String timeRange(DateTime start, DateTime end) =>
      '${time(start)} – ${time(end)}';

  /// Formats a seat count.
  String spots(int count) => count == 1 ? '1 spot left' : '$count spots left';

  /// Formats a session count.
  String sessions(int count) => count == 1 ? '1 session' : '$count sessions';

  /// Formats booked seats against capacity.
  String bookedOf(int booked, int capacity) => '$booked of $capacity booked';

  /// Formats a roster count.
  String bookedCount(int count) => '$count booked';

  /// Human label for a member booking.
  String bookingLabel({
    required String bookingStatus,
    required String classStatus,
    required bool isWaitListed,
  }) {
    if (isWaitListed) return 'Waitlisted';
    if (classStatus == 'Completed') return 'Completed';
    if (classStatus == 'Cancelled') return 'Class cancelled';
    if (bookingStatus == 'Attended') return 'Attended';
    if (bookingStatus == 'NoShow') return 'No show';
    if (bookingStatus == 'Cancelled') return 'Cancelled';
    return 'Confirmed';
  }

